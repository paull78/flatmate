// Builds packages/editor/src/view/inter-widths.ts from Inter's TTF (render.15): the advance width of each Windows-1252
// byte's glyph, read from the font's head, hhea, hmtx and cmap tables. No dependencies, and the same file in gives the
// same text out.

/** Windows-1252's 0x80–0x9F, by byte; the five bytes it leaves undefined are missing. Every other byte from 0x20 is
 * its own code point. */
const CP1252_EXTRAS: Record<number, number> = {
  0x80: 0x20ac, 0x82: 0x201a, 0x83: 0x0192, 0x84: 0x201e, 0x85: 0x2026, 0x86: 0x2020, 0x87: 0x2021, 0x88: 0x02c6,
  0x89: 0x2030, 0x8a: 0x0160, 0x8b: 0x2039, 0x8c: 0x0152, 0x8e: 0x017d, 0x91: 0x2018, 0x92: 0x2019, 0x93: 0x201c,
  0x94: 0x201d, 0x95: 0x2022, 0x96: 0x2013, 0x97: 0x2014, 0x98: 0x02dc, 0x99: 0x2122, 0x9a: 0x0161, 0x9b: 0x203a,
  0x9c: 0x0153, 0x9e: 0x017e, 0x9f: 0x0178,
};
const QUESTION = 0x3f;
const SOFT_HYPHEN = 0xad;

/** The character a byte stands for, or "?" for control bytes and bytes Windows-1252 leaves undefined. toWinAnsi never
 * produces those, so their entries only keep the table total. */
function codePointOf(byte: number): number {
  if ((byte >= 0x20 && byte <= 0x7e) || byte >= 0xa0) return byte;
  return CP1252_EXTRAS[byte] ?? QUESTION;
}

interface Font {
  unitsPerEm: number;
  revision: number;
  ascent: number; // hhea, font units above the baseline
  descent: number; // hhea, font units below the baseline (positive)
  advanceOf(codePoint: number): number;
}

function readFont(ttf: Uint8Array): Font {
  const view = new DataView(ttf.buffer, ttf.byteOffset, ttf.byteLength);
  const tables = new Map<string, number>();
  for (let i = 0, n = view.getUint16(4); i < n; i++) {
    const record = 12 + 16 * i;
    tables.set(String.fromCharCode(...ttf.subarray(record, record + 4)), view.getUint32(record + 8));
  }
  const table = (tag: string): number => {
    const offset = tables.get(tag);
    if (offset === undefined) throw new Error(`the font has no ${tag} table`);
    return offset;
  };

  const head = table("head");
  const hhea = table("hhea");
  const numberOfHMetrics = view.getUint16(hhea + 34);
  const hmtx = table("hmtx");
  const advanceOfGlyph = (glyph: number): number => view.getUint16(hmtx + 4 * Math.min(glyph, numberOfHMetrics - 1));

  // cmap: the format 4 subtable for platform 3 (Windows), encoding 1 (Unicode BMP).
  const cmap = table("cmap");
  let subtable: number | undefined;
  for (let i = 0, n = view.getUint16(cmap + 2); i < n; i++) {
    const record = cmap + 4 + 8 * i;
    if (view.getUint16(record) === 3 && view.getUint16(record + 2) === 1) subtable = cmap + view.getUint32(record + 4);
  }
  if (subtable === undefined || view.getUint16(subtable) !== 4) throw new Error("the font has no (3, 1) format 4 cmap");
  const segments = view.getUint16(subtable + 6) / 2;
  const endCodes = subtable + 14;
  const startCodes = endCodes + 2 * segments + 2;
  const idDeltas = startCodes + 2 * segments;
  const idRangeOffsets = idDeltas + 2 * segments;

  function glyphOf(codePoint: number): number {
    for (let s = 0; s < segments; s++) {
      if (view.getUint16(endCodes + 2 * s) < codePoint) continue;
      const start = view.getUint16(startCodes + 2 * s);
      if (codePoint < start) return 0;
      const rangeOffset = view.getUint16(idRangeOffsets + 2 * s);
      const delta = view.getUint16(idDeltas + 2 * s);
      if (rangeOffset === 0) return (codePoint + delta) & 0xffff;
      const glyph = view.getUint16(idRangeOffsets + 2 * s + rangeOffset + 2 * (codePoint - start));
      return glyph === 0 ? 0 : (glyph + delta) & 0xffff;
    }
    return 0;
  }

  return {
    unitsPerEm: view.getUint16(head + 18),
    revision: view.getInt32(head + 4) / 65536,
    ascent: view.getInt16(hhea + 4),
    descent: -view.getInt16(hhea + 6),
    advanceOf(codePoint) {
      const glyph = glyphOf(codePoint);
      if (glyph === 0) throw new Error(`the font has no glyph for U+${codePoint.toString(16).padStart(4, "0")}`);
      return advanceOfGlyph(glyph);
    },
  };
}

/** The text of inter-widths.ts for this TTF. */
export function interWidthsSource(ttf: Uint8Array): string {
  const font = readFont(ttf);
  if (font.unitsPerEm !== 2048) throw new Error(`expected 2048 units per em, the font has ${font.unitsPerEm}`);
  // Inter has no soft hyphen: it is invisible mid-line (a default-ignorable character), so it measures 0.
  const widths = Array.from({ length: 256 }, (_, byte) => (byte === SOFT_HYPHEN ? 0 : font.advanceOf(codePointOf(byte))));
  const rows = Array.from({ length: 16 }, (_, r) => `  ${widths.slice(16 * r, 16 * r + 16).join(", ")},`);
  return [
    `// Generated by scripts/inter-widths.ts from packages/editor/fonts/Inter-Regular.ttf (font revision ${font.revision.toFixed(3)}).`,
    "// Do not edit: run `pnpm exec tsx scripts/inter-widths.ts`. Inter Regular's advance width per Windows-1252 byte, in",
    "// font units; control and undefined bytes measure as \"?\", the soft hyphen (no glyph) 0. Read through toWinAnsi.",
    "",
    `export const INTER_UNITS_PER_EM = ${font.unitsPerEm};`,
    "// hhea's ascent and descent, in font units: the line box text plates are measured with.",
    `export const INTER_ASCENT = ${font.ascent};`,
    `export const INTER_DESCENT = ${font.descent};`,
    "",
    "// prettier-ignore",
    "export const INTER_WIDTHS: readonly number[] = [",
    ...rows,
    "];",
    "",
  ].join("\n");
}
